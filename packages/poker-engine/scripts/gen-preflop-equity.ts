/**
 * Writes src/preflopEquity.ts: all-in preflop equity of every starting hand class against every other
 * (169 × 169, grid order), by Monte Carlo over random combos of both classes and random boards.
 * The push/fold solver uses it, so the app doesn't simulate thousands of boards on the phone.
 *
 *   tsx scripts/gen-preflop-equity.ts [samples per pair, default 10000] [part] [parts]
 *
 * With part/parts it computes only some rows and writes a JSON chunk; run without them to merge.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { Card } from '../src/cards';
import { evaluate } from '../src/evaluator';
import { classCombos, gridClass } from '../src/ranges';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const samples = Number(process.argv[2] ?? 10_000);
const part = process.argv[3] === undefined ? null : Number(process.argv[3]);
const parts = Number(process.argv[4] ?? 1);

const N = 169;
const classes = Array.from({ length: N }, (_, i) => gridClass(Math.floor(i / 13), i % 13));
const combos = classes.map((c) => classCombos(c));

/** Upper-triangle index of the pair (i < j). */
const pairIndex = (i: number, j: number) => i * N - (i * (i + 1)) / 2 + (j - i - 1);
const PAIRS = (N * (N - 1)) / 2;

// sfc32: a small, fast generator with good statistical quality; seeded so the table is reproducible.
let sa = 0x9e3779b9 | 0;
let sb = 0x243f6a88 | 0;
let sc = 0xb7e15162 | 0;
let sd = 1;
function next(): number {
  const t = (((sa + sb) | 0) + sd) | 0;
  sd = (sd + 1) | 0;
  sa = sb ^ (sb >>> 9);
  sb = (sc + (sc << 3)) | 0;
  sc = (sc << 21) | (sc >>> 11);
  sc = (sc + t) | 0;
  return (t >>> 0) / 4294967296;
}
for (let i = 0; i < 32; i++) next();
const pick = (n: number) => Math.floor(next() * n);

function pairEquity(i: number, j: number): number {
  const a = combos[i]!;
  const b = combos[j]!;
  const used = new Uint8Array(52);
  const deck: Card[] = [];
  const h1: Card[] = [0, 0, 0, 0, 0, 0, 0];
  const h2: Card[] = [0, 0, 0, 0, 0, 0, 0];
  let share = 0;
  let done = 0;
  while (done < samples) {
    const [a1, a2] = a[pick(a.length)]!;
    const [b1, b2] = b[pick(b.length)]!;
    if (a1 === b1 || a1 === b2 || a2 === b1 || a2 === b2) continue;
    used.fill(0);
    used[a1] = used[a2] = used[b1] = used[b2] = 1;
    deck.length = 0;
    for (let c = 0; c < 52; c++) if (!used[c]) deck.push(c);
    for (let k = 0; k < 5; k++) {
      const r = k + pick(deck.length - k);
      const t = deck[k]!;
      deck[k] = deck[r]!;
      deck[r] = t;
    }
    h1[0] = a1;
    h1[1] = a2;
    h2[0] = b1;
    h2[1] = b2;
    for (let k = 0; k < 5; k++) h1[k + 2] = h2[k + 2] = deck[k]!;
    const v1 = evaluate(h1);
    const v2 = evaluate(h2);
    share += v1 > v2 ? 1 : v1 === v2 ? 0.5 : 0;
    done++;
  }
  return share / samples;
}

if (part !== null) {
  const out: Record<number, number> = {};
  for (let i = part; i < N; i += parts) {
    for (let j = i + 1; j < N; j++) out[pairIndex(i, j)] = Math.round(pairEquity(i, j) * 1000);
  }
  writeFileSync(join(root, `scripts/.equity-part-${part}.json`), JSON.stringify(out));
  console.log(`part ${part} done`);
} else {
  const table = new Array<number>(PAIRS).fill(-1);
  for (let p = 0; existsSync(join(root, `scripts/.equity-part-${p}.json`)); p++) {
    const chunk = JSON.parse(readFileSync(join(root, `scripts/.equity-part-${p}.json`), 'utf8')) as Record<string, number>;
    for (const [k, v] of Object.entries(chunk)) table[Number(k)] = v;
  }
  if (table.includes(-1)) throw new Error('Missing parts: run every part first');
  const lines: string[] = [];
  for (let k = 0; k < table.length; k += 40) lines.push('  ' + table.slice(k, k + 40).join(','));
  writeFileSync(
    join(root, 'src/preflopEquity.ts'),
    `// Generated by scripts/gen-preflop-equity.ts (${samples} samples per pair): do not edit by hand.\n` +
      `/** All-in preflop equity of hand class i against class j for i < j in grid order, in thousandths. */\n` +
      `export const PREFLOP_EQUITY_PERMILLE: readonly number[] = [\n${lines.join(',\n')},\n];\n`,
  );
  console.log(`wrote ${table.length} pairs`);
}
