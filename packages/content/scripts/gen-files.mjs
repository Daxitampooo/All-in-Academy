#!/usr/bin/env node
// Writes src/lessonFiles.ts and src/rangeFiles.ts from the folders in lessons/ and ranges/.
// Metro and TypeScript need static imports, so the lists are generated: run `pnpm gen` after adding
// a lesson folder or a range file. A test fails if the lists are out of date.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const camel = (s) => s.replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase()).replace(/^[0-9]/, (d) => `n${d}`);

const lessons = readdirSync(join(root, 'lessons')).sort();
let out = `// Generated by scripts/gen-files.mjs from the lessons/ folders: do not edit by hand.\nimport type { LessonMeta, LessonText } from './types';\n\n`;
for (const id of lessons) {
  const v = camel(id);
  out += `import ${v}Meta from '../lessons/${id}/meta.json';\nimport ${v}En from '../lessons/${id}/en.json';\nimport ${v}Ru from '../lessons/${id}/ru.json';\n`;
}
out += `\nexport const LESSON_FILES: { meta: LessonMeta; en: LessonText; ru: LessonText }[] = [\n`;
for (const id of lessons) {
  const v = camel(id);
  out += `  { meta: ${v}Meta as LessonMeta, en: ${v}En, ru: ${v}Ru },\n`;
}
out += `];\n`;
writeFileSync(join(root, 'src/lessonFiles.ts'), out);

const ranges = readdirSync(join(root, 'ranges')).filter((f) => f.endsWith('.json')).sort();
let r = `// Generated by scripts/gen-files.mjs from the ranges/ folder: do not edit by hand.\nimport type { RangeSpec } from './types';\n\n`;
for (const f of ranges) r += `import r${camel(f.replace('.json', ''))} from '../ranges/${f}';\n`;
r += `\nexport const RANGE_FILES: RangeSpec[] = [${ranges.map((f) => `r${camel(f.replace('.json', ''))}`).join(', ')}] as RangeSpec[];\n`;
writeFileSync(join(root, 'src/rangeFiles.ts'), r);
console.log(`${lessons.length} lessons, ${ranges.length} ranges`);
