// Computes how strong each of the 169 starting hands is against one random
// hand (all-in preflop equity) and writes src/preflop-table.ts.
// Run: pnpm --filter @pokerall/bots gen:preflop
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  classCombos,
  createSeededRng,
  gridClass,
  parseRange,
  rangeCombos,
  rangeEquity,
  seedFromHex,
} from '../../poker-engine/src';

const rng = createSeededRng(seedFromHex('5a'.repeat(32)));
const anyTwo = parseRange('22+, A2+, K2+, Q2+, J2+, T2+, 92+, 82+, 72+, 62+, 52+, 42+, 32');
const iterations = 60_000;

const rows: { cls: string; equity: number; combos: number }[] = [];
for (let r = 0; r < 13; r++) {
  for (let c = 0; c < 13; c++) {
    const cls = gridClass(r, c);
    const hand = classCombos(cls)[0]!;
    const result = rangeEquity([{ cards: hand }, { range: rangeCombos(anyTwo, hand) }], [], { rng, iterations });
    rows.push({ cls, equity: result.equity[0]!, combos: classCombos(cls).length });
  }
}
rows.sort((a, b) => b.equity - a.equity);
let cumulative = 0;
const entries = rows.map((row) => {
  cumulative += row.combos;
  // Share of all 1326 combos that are this strong or stronger.
  return `  ${JSON.stringify(row.cls)}: [${row.equity.toFixed(4)}, ${(cumulative / 1326).toFixed(4)}],`;
});

const out = `// Generated by scripts/gen-preflop-table.ts — do not edit by hand.
// [equity against one random hand, share of combos at least this strong]
export const PREFLOP_TABLE: Record<string, readonly [number, number]> = {
${entries.join('\n')}
};
`;
writeFileSync(join(__dirname, '../src/preflop-table.ts'), out);
console.log('Wrote', rows.length, 'hands. Top:', rows.slice(0, 5).map((r) => r.cls).join(' '), 'Bottom:', rows.at(-1)!.cls);
